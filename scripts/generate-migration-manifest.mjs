#!/usr/bin/env node
/**
 * Bakes the list of supabase/migrations/*.sql basenames into
 * lib/db/migration-manifest.ts, so the drift checker can compare "what the
 * repo has" against "what the DB says it applied" at runtime.
 *
 * Generated rather than read from disk because the .sql files aren't
 * imported by any module, so Next's output tracing doesn't ship them to
 * the serverless bundle — at runtime in production the directory simply
 * isn't there. Runs from `prebuild`, so a deploy always carries the
 * migration list matching the code being deployed.
 *
 * Deliberately fail-soft: if this can't read the directory it leaves any
 * existing manifest alone and exits 0. A drift *checker* that breaks the
 * build would be a worse outcome than the drift it's watching for.
 */

import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = join(root, 'supabase', 'migrations')
const outFile = join(root, 'lib', 'db', 'migration-manifest.ts')

if (!existsSync(migrationsDir)) {
  console.warn('[migration-manifest] no supabase/migrations dir — leaving manifest untouched')
  process.exit(0)
}

let names
try {
  names = readdirSync(migrationsDir)
    .filter((f) => f.endsWith('.sql'))
    .map((f) => f.replace(/\.sql$/, ''))
    .sort()
} catch (err) {
  console.warn('[migration-manifest] read failed, leaving manifest untouched:', err.message)
  process.exit(0)
}

const body = `// GENERATED by scripts/generate-migration-manifest.mjs — do not edit by hand.
// Regenerated on every build via the \`prebuild\` npm script.
//
// The repo's migration filenames, baked in at build time because the .sql
// files themselves never reach the serverless bundle. Compared against the
// DB's applied ledger by lib/db/migration-drift.ts.

export const REPO_MIGRATIONS: readonly string[] = [
${names.map((n) => `  '${n}',`).join('\n')}
]
`

writeFileSync(outFile, body)
console.log(`[migration-manifest] wrote ${names.length} migrations to lib/db/migration-manifest.ts`)
